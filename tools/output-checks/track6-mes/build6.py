# Builds site/data/tracks/06-mes.js from lessons6.py, with every "What it produces" text taken
# from compiling and running the lesson's C# code.  Needs the .NET 8 SDK.
#   cd tools/output-checks/track6-mes && python3 build6.py
#
# How the outputs are made:
#   - Models.cs is the lesson code. Db.cs is swapped for FakeDb.cs, which returns the Shift
#     Handoff sample data. Program.cs is built one step at a time; each step's output is the
#     lines it adds to the previous step's output. Run time: 2026-11-07T14:05.
#   - The last step also runs the finished program a second time against the same stand-in
#     store, to show that a rerun posts nothing new.
#   - The real Db.cs is compiled too, so the SQL Server code is checked even though it is not run.
import json, os, re, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT_JS = ROOT / "site/data/tracks/06-mes.js"
BUILD = HERE / "build"
RUN_AT = "2026-11-07T14:05"
SQLCLIENT = "7.1.1"

sys.path.insert(0, str(HERE))
from lessons6 import TRACK, L  # noqa: E402

for l in L:
    l["code"] = l["code"].strip("\n")

ENV = dict(os.environ, DOTNET_CLI_TELEMETRY_OPTOUT="1", DOTNET_NOLOGO="1")
CSPROJ = f"""<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net8.0</TargetFramework>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <AssemblyName>MesHelper</AssemblyName>
  </PropertyGroup>
  <ItemGroup>
    <PackageReference Include="Microsoft.Data.SqlClient" Version="{SQLCLIENT}" />
  </ItemGroup>
</Project>
"""


def file_code(name, upto=None):
    steps = [l for i, l in enumerate(L) if l["file"] == name and (upto is None or i <= upto)]
    return "\n\n".join(l["code"] for l in steps) + "\n"


def project(dirname, files):
    d = BUILD / dirname
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    (d / "MesHelper.csproj").write_text(CSPROJ)
    for n, text in files.items():
        (d / n).write_text(text)
    return d


def sh(args, cwd, env=ENV):
    r = subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True)
    return r


def build(d):
    r = sh(["dotnet", "build", "-nologo", "-v", "q", "-clp:NoSummary;ErrorsOnly"], d)
    if r.returncode != 0:
        print(r.stdout[-3000:], r.stderr[-2000:])
        raise SystemExit(f"Build failed in {d}")


def run(d, store):
    env = dict(ENV, MES_STORE=str(store))
    r = sh(["dotnet", "run", "--no-build", "--", RUN_AT], d, env)
    return r.returncode, r.stdout.rstrip("\n"), r.stderr.strip()


BUILD.mkdir(exist_ok=True)
models = file_code("Models.cs")
fake = (HERE / "FakeDb.cs").read_text()

# 1. The real project (lesson Db.cs) must compile.
real = project("real", {"Models.cs": models, "Db.cs": file_code("Db.cs"), "Program.cs": file_code("Program.cs")})
build(real)
print("real project (with SQL Server Db.cs) builds")

# 2. Run Program.cs step by step against the stand-in.
outs = {}
prev = []
prog_idx = [i for i, l in enumerate(L) if l["file"] == "Program.cs"]
for i in prog_idx:
    d = project(f"step{i + 1:02d}", {"Models.cs": models, "Db.cs": fake, "Program.cs": file_code("Program.cs", i)})
    build(d)
    store = d / "mes_store.json"
    code, out, err = run(d, store)
    lines = out.split("\n") if out else []
    if lines[: len(prev)] != prev:
        raise SystemExit(f"step {i + 1}: output is not an extension of the previous step's output")
    new = lines[len(prev):]
    while new and not new[0].strip():
        new = new[1:]
    text = "\n".join(new)
    if L[i]["t"] == "Save a CSV for the shift":
        csv_name = re.search(r"Saved (\S+)", text).group(1)
        text += f"\n\n{csv_name}:\n" + (d / csv_name).read_text().rstrip("\n")
    if i == prog_idx[-1]:
        code2, out2, err2 = run(d, store)
        text += "\n\nRun again for the same shift:\n" + out2.split("\n")[-1]
        text += f"\n\nExit code: {code} (first run), {code2} (second run)"
        if code != 0 or code2 != 0:
            raise SystemExit(f"unexpected exit codes {code}, {code2}: {err} {err2}")
    if err:
        raise SystemExit(f"step {i + 1} wrote to stderr: {err}")
    outs[i] = text
    prev = lines
    print(f"===== step {i + 1} {L[i]['t']}\n{text}")


# 3. Write the JS file.
def js_str(s):
    return "`" + s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${") + "`"


def js_q(s):
    return json.dumps(s, ensure_ascii=False)


parts = [
    "// Project track 6: MES Helper",
    "// Generated by tools/output-checks/track6-mes/build6.py from lessons6.py. Edit lessons6.py, not this file.",
    "BC.addTrack({",
    f"  id: {js_q(TRACK['id'])},",
    f"  name: {js_q(TRACK['name'])},",
    f"  sub: {js_q(TRACK['sub'])},",
    "  lessons: [",
]
for i, l in enumerate(L):
    parts.append("    {")
    parts.append(f"      lang: {js_q(l['lang'])},")
    parts.append(f"      file: {js_q(l['file'])},")
    parts.append(f"      t: {js_q(l['t'])},")
    parts.append(f"      goal: {js_q(l['goal'])},")
    parts.append(f"      code: {js_str(l['code'])},")
    parts.append(f"      about: {js_q(l['about'])},")
    parts.append("      terms: [")
    for k, lab, d in l["terms"]:
        parts.append(f"        [{js_q(k) if k is not None else 'null'}, {js_q(lab)}, {js_q(d)}],")
    parts.append("      ],")
    if i in outs and outs[i]:
        parts.append(f"      out: {js_str(outs[i])},")
    parts.append("    },")
parts += ["  ],", "});", ""]
OUT_JS.write_text("\n".join(parts))
print(f"\nWrote {OUT_JS.relative_to(ROOT)}: {len(L)} steps, {len(outs)} with output")
