# Builds site/data/tracks/24-energy.js from steps24.py and lessons24.py. SQL steps run one at a time
# through foundations/sql_exec.py on a fresh PlantDB (energy_log included); a step that reads
# v_hourly_barrels gets the OEE track's view first, from that lesson's own code. Python steps run in
# sequence, as one file, with the same view. Checks: the first step's CREATE equals ENERGY_DDL in
# sql_exec.py; the hours with a pressure dip are the hours a low-air stop starts in fault_log; and the
# energy saved after the leak repairs is the Savings Tracker's $165 a week for P1, within $1.
# Needs BC_SQL_PASSWORD and the SQL Server container. Do not edit the JS file by hand.
#   python3 build24.py            write the track
#   python3 build24.py --check    report a difference, change nothing
import contextlib, io, json, os, re, subprocess, sys, tempfile, warnings
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "lib" / "pydb"))
sys.path.insert(0, str(HERE.parent / "foundations"))
import plantdb
from steps24 import CODE, LANG

def ddl():
    src = (HERE.parent / "foundations/sql_exec.py").read_text()
    return re.search(r'ENERGY_DDL = """(.*?)"""', src, re.S).group(1)

if CODE["Create energy_log"] != ddl():
    sys.exit("Create energy_log differs from ENERGY_DDL in sql_exec.py: keep them the same")

def lesson_code(track_file, title):
    js = ("const fs=require('fs'),vm=require('vm'),c={};c.BC={addLanguage(){},addGlossary(){},addLane(){},addTrack(t){c.t=t}};"
          "vm.createContext(c);vm.runInContext(fs.readFileSync(process.argv[1],'utf8'),c);"
          "console.log(JSON.stringify(c.t.lessons.find(l=>l.t===process.argv[2]).code))")
    return json.loads(subprocess.run(["node", "-e", js, str(ROOT / "site/data/tracks" / track_file), title], capture_output=True, text=True, check=True).stdout)

# A CREATE prints nothing, so its output is a check query on what it made, printed above its result.
AFTER = {"Create energy_log": "SELECT COLUMN_NAME AS column_name, DATA_TYPE AS type, IS_NULLABLE AS nullable\n"
         "FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'energy_log' ORDER BY ORDINAL_POSITION;"}
OEE_VIEW = lesson_code("03-oee.js", "Hourly barrels view")
outs = {}
for title, lang in LANG.items():
    if lang == "sql":
        src = (OEE_VIEW + "\nGO\n" + CODE[title]) if "v_hourly_barrels" in CODE[title] else CODE[title]
        r = subprocess.run([sys.executable, str(HERE.parent / "foundations/sql_exec.py")], input=src, capture_output=True, text=True,
                           env={**os.environ, "BC_SQL_AFTER": AFTER.get(title, "")})
        if r.returncode:
            sys.exit(f"{title}: {r.stderr}")
        outs[title] = r.stdout.rstrip()

plantdb.reset([OEE_VIEW])
plantdb.use_real_database()
warnings.filterwarnings("ignore", message="pandas only supports SQLAlchemy")
g = {}
with tempfile.TemporaryDirectory() as d:
    os.chdir(d)  # the KPI step saves an .xlsx
    for title, lang in LANG.items():
        if lang != "python":
            continue
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            exec(CODE[title], g)
        outs[title] = buf.getvalue().rstrip()

# Cross-checks on the same database the Python steps used.
cur = g["conn"].cursor()
cur.execute("""SELECT COUNT(*) FROM energy_log AS e
               FULL JOIN (SELECT DISTINCT DATEADD(HOUR, DATEDIFF(HOUR, 0, start_ts) + 1, 0) AS h FROM fault_log WHERE fault = 'Low air') AS f
                 ON f.h = e.hour_end
               WHERE e.hour_end <= '2026-11-07 06:00' AND ((e.min_psi < 85 AND f.h IS NULL) OR (e.min_psi >= 85 AND f.h IS NOT NULL))""")
if cur.fetchone()[0]:
    sys.exit("Pressure dips in the OEE week do not line up with fault_log's low-air stops")
energy = re.search(r"ENERGY_USD_PER_WEEK = \{\"P1\": ([\d.]+)\}", (HERE.parent / "track14-savings/steps14.py").read_text())
if abs(g["saved"] - float(energy.group(1))) > 1:
    sys.exit(f"Energy saved ${g['saved']:.2f} a week is not the Savings Tracker's ${energy.group(1)} for P1")

if "--outs" in sys.argv:
    for t, o in outs.items():
        print(f"===== {t}\n{o}")
    sys.exit(0)
print("Cross-checks: CREATE matches the seed's DDL; dips line up with low-air stops; energy saved matches the Savings Tracker's P1 within $1")

from lessons24 import TRACK, LESSONS
assert [t for t, *_ in LESSONS] == list(CODE), "lessons24.py and steps24.py list different steps"

def whole(k, code):
    pre = r"(?<!\w)" if re.match(r"\w", k) else ""
    post = r"(?!\w)" if re.search(r"\w$", k) else ""
    return re.search(pre + re.escape(k) + post, code) is not None

tpl = lambda x: "`" + x.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${") + "`"
js = lambda v: json.dumps(v, ensure_ascii=False)
lines = ["// Project track 24: Energy / Utilities (SQL and Python on the plant database)",
         "// Generated by tools/output-checks/track24-energy/build24.py from steps24.py and lessons24.py. Do not edit by hand.",
         "BC.addTrack({", f"  id: {js(TRACK['id'])},", f"  name: {js(TRACK['name'])},", f"  sub: {js(TRACK['sub'])},", "  lessons: ["]
for title, goal, about, terms in LESSONS:
    code = CODE[title]
    for k, *_ in terms:
        if k is not None and not whole(k, code):
            sys.exit(f"{title}: term key {k!r} is not in the code")
    lines += ["    {", f"      lang: {js(LANG[title])},", f"      file: {js(TRACK['files'][LANG[title]])},", f"      t: {js(title)},", f"      goal: {js(goal)},",
              f"      code: {tpl(code)},", f"      about: {js(about)},", "      terms: ["]
    lines += [f"        [{'null' if k is None else js(k)}, {js(a)}, {js(b)}]," for k, a, b in terms]
    lines += ["      ],", f"      out: {tpl(outs[title])},", "    },"]
lines += ["  ],", "});", ""]
text = "\n".join(lines)
target = ROOT / "site/data/tracks/24-energy.js"
if "--check" in sys.argv:
    same = target.exists() and target.read_text() == text
    print("24-energy.js is current" if same else "24-energy.js is stale: run python3 build24.py")
    sys.exit(0 if same else 1)
target.write_text(text)
print(f"wrote {target.relative_to(ROOT)}: {len(LESSONS)} steps")
